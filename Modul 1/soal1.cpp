#include <iostream>
using namespace std;

int main() {
    float x;
    float y;
    
    cout << "input x: ";
    cin >> x;
    cout << "input y: ";
    cin >> y;

    cout << "Hasil Penjumlahan : " << x + y << endl;
    cout << "Hasil Pengurangan : " << x - y << endl;
    cout << "Hasil Perkalian   : " << x * y << endl;
    return 0;
}